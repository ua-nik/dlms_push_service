class OBISRegistry:
    """
    Централізований доступ до метаданих OBIS-кодів.
    """

    @classmethod
    def get(cls, obis_code: str) -> Optional[OBISInfo]:
        if not obis_code:
            return None
        return OBIS_DEFINITIONS.get(obis_code.strip())

    @classmethod
    def get_name(cls, obis_code: str, lang: str = "en") -> str:
        info = cls.get(obis_code)
        if not info:
            return obis_code
        if lang == "ua" and info.name_ua:
            return info.name_ua
        return info.name_en or info.name_ua or obis_code

    @classmethod
    def get_unit(cls, obis_code: str) -> str:
        info = cls.get(obis_code)
        return info.unit if info else ""

    @classmethod
    def format_parameter(
        cls,
        obis_code: str,
        value: Any,
        unit: Optional[str] = None,
        scaler: int = 0,
        attribute_id: int = 2,
        dtype: Optional[str] = None,
        lang: str = "en",
    ) -> Dict[str, Any]:
        info = cls.get(obis_code)
        name = cls.get_name(obis_code, lang=lang)
        default_unit = info.unit if info else ""
        final_unit = unit if unit is not None else default_unit
        class_id = info.class_id if info else 3
        param_dtype = dtype or (info.dtype if info else "UNKNOWN")
        return {
            "name": name,
            "name_en": info.name_en if info else obis_code,
            "name_ua": info.name_ua if info else obis_code,
            "obis": obis_code,
            "class_id": class_id,
            "attribute_id": attribute_id,
            "type": param_dtype,
            "value": str(value),
            "unit": final_unit,
            "scaler": scaler,
        }
